package com.easycount.entity;

import java.math.BigDecimal;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

@Entity
@Table(name = "sales_return_items")
@Getter
@Setter
@NoArgsConstructor
public class SalesReturnItem {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "sales_return_id", nullable = false)
    private SalesReturn salesReturn;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "sale_item_id", nullable = false)
    private SaleItem saleItem;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "item_id", nullable = false)
    private Item item;

    @Column(name = "qty", nullable = false)
    private BigDecimal qty;

    @Column(name = "price", nullable = false)
    private BigDecimal price;

    // Generated by PostgreSQL
    @Column(name = "line_total", insertable = false, updatable = false)
    private BigDecimal lineTotal;

    public SalesReturnItem(
            SalesReturn salesReturn,
            SaleItem saleItem,
            BigDecimal qty,
            BigDecimal price) {

        this.salesReturn = salesReturn;
        this.saleItem = saleItem;
        this.item = saleItem.getItem();
        this.qty = qty;
        this.price = price;
    }
}